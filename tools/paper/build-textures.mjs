// Writes src/serigraph/styles/textures.generated.css: the printed grain, as seamless SVG tiles in data URIs (text, so
// they ship through the shadcn registry). The grain is neutral, so one set serves every colourway: ink specks, paper
// flecks, a fine tooth and a slow mottle, at tile sizes that share no factors. base.css stacks them as --grain.
//
//   npm run build:textures
import { writeFileSync } from "node:fs"
import { flecks, relief, tinted } from "./layers.mjs"

const INK = "#262420"
const PAPER = "#eae3c8"

const layers = {
  // Ink pressed into the stock: small dark specks, the odd larger chip.
  specks: flecks(541, 260, 7, [
    [INK, 0.28],
    [INK, 0.18],
  ]),
  // Paper showing through the ink film: light flecks.
  flecks: flecks(613, 220, 11, [
    [PAPER, 0.42],
    ["#ffffff", 0.3],
  ]),
  // The tooth of heavy poster stock, embossed light and dark.
  tooth: relief(353, 0.6, 3, 0.1, [0.15, 0.14, 0.12]),
  // A slow, faint unevenness in how the ink lay down.
  mottle: tinted(1201, 0.004, 4, 41, [0.15, 0.14, 0.12], 0.14, -0.05),
}

const css = `/* Generated by tools/paper/build-textures.mjs. Edit the layers there, then rerun it. */
:root {
${Object.entries(layers)
  .map(([name, url]) => `  --tex-${name}: ${url};`)
  .join("\n")}
}
`
const file = new URL(
  "../../src/serigraph/styles/textures.generated.css",
  import.meta.url,
)
writeFileSync(file, css)
console.log(
  `wrote ${file.pathname}: ${Object.keys(layers).length} grain layers, ${(css.length / 1024).toFixed(0)} KB`,
)
